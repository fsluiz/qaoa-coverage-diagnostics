#!/usr/bin/env python3
"""Audit the scope of exact circuit factorisation.

The exact theorem is algebraic: block-local cost and driver layers make the
layered unitary a tensor product over the common variable partition, for any
input.  A product output additionally requires an initial state that is a
product across that partition; each block may be internally entangled.
Geometry is used only to test a sufficient locality relation for radius-R coverage,

    edge in G_ZZ  =>  base distance <= 2R.

The program checks random incidence hypergraphs, explicit counterexamples, and
spatial ensembles generated by four point processes and two target models.

Writes results/factorisation_scope.json.
"""
from __future__ import annotations

import json
import math
from collections import Counter, defaultdict

import numpy as np
from scipy.sparse import csr_matrix
from scipy.sparse.csgraph import connected_components

from _paths import RESULTS_DIR


def interaction_graph(A: np.ndarray) -> np.ndarray:
    B = np.asarray(A, dtype=np.int64)
    graph = (B.T @ B) > 0
    np.fill_diagonal(graph, False)
    return graph


def components(graph: np.ndarray) -> tuple[int, np.ndarray, list[int]]:
    count, labels = connected_components(csr_matrix(graph), directed=False)
    sizes = sorted(Counter(labels.tolist()).values(), reverse=True)
    return int(count), labels, sizes


def direct_sum_check(A: np.ndarray, labels: np.ndarray) -> bool:
    for row in A:
        support = np.flatnonzero(row)
        if len(support) and len(set(labels[support].tolist())) != 1:
            return False
    return True


def log2_enumeration_cost(sizes: list[int]) -> float:
    largest = max(sizes)
    return float(largest + math.log2(sum(2.0 ** (size - largest) for size in sizes)))


def pairwise_distance(left: np.ndarray, right: np.ndarray) -> np.ndarray:
    return np.linalg.norm(left[:, None, :] - right[None, :, :], axis=2)


def sample_points(family: str, n: int, rng: np.random.Generator) -> np.ndarray:
    if family == "uniform_plane":
        return rng.uniform(0.0, 1.0, size=(n, 2))
    if family == "corridor":
        return np.column_stack((rng.uniform(0.0, 4.0, n), rng.normal(0.0, 0.06, n)))
    if family == "clustered":
        centres = np.asarray([[0.2, 0.2], [0.2, 0.8], [0.8, 0.2], [0.8, 0.8]])
        chosen = centres[rng.integers(0, len(centres), size=n)]
        return chosen + rng.normal(0.0, 0.055, size=(n, 2))
    if family == "jittered_lattice":
        side = int(math.ceil(math.sqrt(n)))
        grid = np.asarray([(i, j) for i in range(side) for j in range(side)], dtype=float)[:n]
        grid /= max(side - 1, 1)
        return grid + rng.normal(0.0, 0.015, size=grid.shape)
    raise ValueError(family)


def nearest_neighbour_scale(points: np.ndarray) -> float:
    D = pairwise_distance(points, points)
    np.fill_diagonal(D, np.inf)
    return float(np.median(D.min(axis=1)))


def make_targets(
    mode: str,
    bases: np.ndarray,
    radius: float,
    rng: np.random.Generator,
) -> np.ndarray:
    n = len(bases)
    if mode == "anchored":
        anchors = bases[rng.integers(0, n, size=n)]
        angle = rng.uniform(0.0, 2.0 * np.pi, size=n)
        radial = 0.7 * radius * np.sqrt(rng.uniform(0.0, 1.0, size=n))
        return anchors + np.column_stack((radial * np.cos(angle), radial * np.sin(angle)))
    if mode == "independent_bbox":
        lo, hi = bases.min(axis=0), bases.max(axis=0)
        return rng.uniform(lo, hi, size=(n, 2))
    raise ValueError(mode)


def spatial_row(
    family: str,
    target_mode: str,
    n: int,
    factor: float,
    seed: int,
) -> dict:
    rng = np.random.default_rng(seed)
    bases = sample_points(family, n, rng)
    delta = nearest_neighbour_scale(bases)
    radius = factor * delta
    targets = make_targets(target_mode, bases, radius, rng)
    A = (pairwise_distance(targets, bases) <= radius).astype(np.int8)
    G = interaction_graph(A)
    n_components, labels, sizes = components(G)

    base_distance = pairwise_distance(bases, bases)
    proximity_2R = base_distance <= (2.0 * radius + 1e-12)
    np.fill_diagonal(proximity_2R, False)
    proximity_components, _, proximity_sizes = components(proximity_2R)
    violations = int(np.sum(np.triu(G & ~proximity_2R, 1)))

    return {
        "family": family,
        "target_mode": target_mode,
        "n_bases": n,
        "radius_over_median_nearest_neighbour": factor,
        "seed": seed,
        "coverage_fraction": float(np.mean(A.sum(axis=1) > 0)),
        "n_ZZ": int(G.sum() // 2),
        "mean_interaction_degree": float(G.sum() / n),
        "n_components_G_ZZ": n_components,
        "largest_component_G_ZZ": sizes[0],
        "largest_component_fraction_G_ZZ": sizes[0] / n,
        "log2_block_enumeration_dimension": log2_enumeration_cost(sizes),
        "n_components_base_proximity_2R": proximity_components,
        "largest_component_base_proximity_2R": proximity_sizes[0],
        "G_ZZ_edges_outside_2R": violations,
        "G_ZZ_is_subgraph_of_base_proximity_2R": violations == 0,
        "G_ZZ_components_refine_2R_components": n_components >= proximity_components,
        "cost_is_direct_sum_over_G_ZZ_components": direct_sum_check(A, labels),
    }


def random_hypergraph_audit(n_trials: int = 250) -> dict:
    rng = np.random.default_rng(20260915)
    passed = 0
    for _ in range(n_trials):
        n = int(rng.integers(4, 65))
        n_terms = int(rng.integers(1, 2 * n + 1))
        A = np.zeros((n_terms, n), dtype=np.int8)
        for t in range(n_terms):
            width = int(rng.integers(1, min(8, n) + 1))
            A[t, rng.choice(n, size=width, replace=False)] = 1
        _, labels, _ = components(interaction_graph(A))
        passed += int(direct_sum_check(A, labels))
    return {
        "trials": n_trials,
        "direct_sum_checks_passed": passed,
        "all_passed": passed == n_trials,
        "qualification": (
            "For the set-cover squared penalty this follows by construction: every "
            "cost hyperedge becomes a clique in the primal interaction graph."
        ),
    }


def counterexamples() -> dict:
    n = 24

    # Sparse does not imply factorised: n-1 pair terms form a connected path.
    path_A = np.zeros((n - 1, n), dtype=np.int8)
    for i in range(n - 1):
        path_A[i, i : i + 2] = 1
    path_G = interaction_graph(path_A)
    path_nc, path_labels, path_sizes = components(path_G)

    # Relatively dense does not imply connected: four independent K6 blocks.
    clique_A = np.zeros((4, n), dtype=np.int8)
    for block in range(4):
        clique_A[block, 6 * block : 6 * (block + 1)] = 1
    clique_G = interaction_graph(clique_A)
    clique_nc, clique_labels, clique_sizes = components(clique_G)

    # One-dimensional radius coverage can still make the interaction graph a path.
    positions = np.arange(n, dtype=float)[:, None]
    targets = (np.arange(n - 1, dtype=float) + 0.5)[:, None]
    radius = 0.51
    geometric_A = (pairwise_distance(targets, positions) <= radius).astype(np.int8)
    geometric_nc, _, geometric_sizes = components(interaction_graph(geometric_A))

    return {
        "sparse_connected_path": {
            "n_variables": n,
            "n_interactions": int(path_G.sum() // 2),
            "n_components": path_nc,
            "largest_component": path_sizes[0],
            "direct_sum": direct_sum_check(path_A, path_labels),
            "lesson": "sparsity alone does not imply exact block factorisation",
        },
        "dense_disconnected_cliques": {
            "n_variables": n,
            "n_interactions": int(clique_G.sum() // 2),
            "n_components": clique_nc,
            "block_sizes": clique_sizes,
            "direct_sum": direct_sum_check(clique_A, clique_labels),
            "lesson": "geometry is not necessary for exact block factorisation",
        },
        "one_dimensional_geometric_path": {
            "n_variables": n,
            "radius": radius,
            "n_components": geometric_nc,
            "largest_component": geometric_sizes[0],
            "lesson": "geometric locality may give low width without giving disconnected blocks",
        },
        "nonproduct_initial_state": {
            "example": "(|01>+|10>)/sqrt(2) across two otherwise independent one-qubit blocks",
            "schmidt_rank": 2,
            "entanglement_entropy_bits": 1.0,
            "lesson": "block-local unitaries preserve this entanglement; they do not turn the state into a product",
        },
        "bridging_driver": {
            "example": "exp(-i beta X_i X_j) with i and j in different cost blocks",
            "lesson": "a mixer edge merges the circuit support blocks even when the cost Hamiltonian is disconnected",
        },
    }


def summarise(rows: list[dict]) -> list[dict]:
    groups: dict[tuple, list[dict]] = defaultdict(list)
    for row in rows:
        key = (
            row["family"],
            row["target_mode"],
            row["n_bases"],
            row["radius_over_median_nearest_neighbour"],
        )
        groups[key].append(row)
    summary = []
    for key, selected in sorted(groups.items()):
        summary.append({
            "family": key[0],
            "target_mode": key[1],
            "n_bases": key[2],
            "radius_over_median_nearest_neighbour": key[3],
            "n_instances": len(selected),
            "mean_coverage_fraction": float(np.mean([r["coverage_fraction"] for r in selected])),
            "median_n_components_G_ZZ": float(np.median([r["n_components_G_ZZ"] for r in selected])),
            "median_largest_component_fraction_G_ZZ": float(
                np.median([r["largest_component_fraction_G_ZZ"] for r in selected])
            ),
            "median_log2_block_enumeration_dimension": float(
                np.median([r["log2_block_enumeration_dimension"] for r in selected])
            ),
        })
    return summary


def main() -> None:
    families = ["uniform_plane", "corridor", "clustered", "jittered_lattice"]
    target_modes = ["anchored", "independent_bbox"]
    sizes = [32, 64, 128]
    factors = [0.7, 1.0, 1.4, 2.0]
    rows = []
    for family in families:
        for target_mode in target_modes:
            for n in sizes:
                for factor in factors:
                    for repeat in range(8):
                        seed = 1_000_000 * families.index(family) + 100_000 * target_modes.index(target_mode)
                        seed += 1_000 * n + 100 * int(round(10 * factor)) + repeat
                        rows.append(spatial_row(family, target_mode, n, factor, seed))

    out = {
        "theorem": {
            "statement": (
                "If every cost and driver layer is a tensor product over a variable "
                "partition, the layered unitary factorises over that partition for any input; "
                "if the initial state is also a product across the partition, so does the output state."
            ),
            "operator_statement": (
                "Block-local layers imply U = tensor_product_i U_i independently of the input state."
            ),
            "state_corollary": (
                "A block-product input remains a block-product output; states may be internally "
                "entangled within each block."
            ),
            "geometry_required": False,
            "set_cover_support_partition": (
                "connected components of the primal graph joining variables that occur in a common cost term"
            ),
            "geometric_sufficient_relation": "for radius-R metric coverage, E(G_ZZ) is a subset of E(G_base(2R))",
            "limitations": [
                "cross-block entanglement prevents product-state factorisation but not operator factorisation",
                "a mixer or preparation gate crossing the partition merges circuit blocks",
                "sparsity does not imply disconnection",
                "low treewidth is a weaker simulation route than exact block factorisation",
            ],
        },
        "random_incidence_hypergraphs": random_hypergraph_audit(),
        "counterexamples": counterexamples(),
        "spatial_design": {
            "families": families,
            "target_modes": target_modes,
            "sizes": sizes,
            "radius_factors": factors,
            "repeats_per_cell": 8,
            "n_instances": len(rows),
        },
        "spatial_checks": {
            "all_costs_direct_sum_over_their_support_components": all(
                r["cost_is_direct_sum_over_G_ZZ_components"] for r in rows
            ),
            "all_G_ZZ_edges_obey_distance_at_most_2R": all(
                r["G_ZZ_is_subgraph_of_base_proximity_2R"] for r in rows
            ),
            "all_G_ZZ_component_partitions_refine_2R_proximity_partition": all(
                r["G_ZZ_components_refine_2R_components"] for r in rows
            ),
        },
        "spatial_summary": summarise(rows),
        "spatial_rows": rows,
    }
    path = RESULTS_DIR / "factorisation_scope.json"
    path.write_text(json.dumps(out, indent=1) + "\n", encoding="utf-8")
    print(f"random hypergraphs: {out['random_incidence_hypergraphs']['direct_sum_checks_passed']}/250")
    print(f"spatial instances: {len(rows)}")
    for name, passed in out["spatial_checks"].items():
        print(f"  {name}: {passed}")
    print(f"-> {path}")


if __name__ == "__main__":
    main()
